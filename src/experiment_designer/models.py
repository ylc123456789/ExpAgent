"""Pydantic data models for experiment design input and output."""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field


# ── Input models ──────────────────────────────────────────────────


class ExistingMethod(BaseModel):
    """A method or code the user already has."""

    name: str
    location: str | None = Field(default=None, description="File or directory path")
    description: str = ""


class ExistingAssets(BaseModel):
    """What the user already has — code, data, known baselines.

    ExpAgent uses this to avoid planning duplicate work.
    The LLM infers everything else (missing baselines, ablations, etc.).
    """

    implemented_methods: list[ExistingMethod] = Field(default_factory=list)
    available_datasets: list[str] = Field(default_factory=list)
    known_baselines: list[str] = Field(default_factory=list)


class ComputeBudget(BaseModel):
    """Hardware and time constraints for the experiment."""

    gpu: str = "CPU only"
    max_runtime: str = "2 hours"
    max_trials: int = 10


class DesignInput(BaseModel):
    """Everything the user provides to kick off experiment design."""

    research_idea: str = Field(description="Natural language description of the research idea")
    target_task: str = Field(description="Task domain, e.g. 'image classification', 'time series forecasting'")
    compute_budget: ComputeBudget = Field(default_factory=ComputeBudget)
    constraints: list[str] = Field(default_factory=list)
    literature_context: list[str] = Field(default_factory=list)
    existing_assets: ExistingAssets = Field(default_factory=ExistingAssets)


# ── Output models ─────────────────────────────────────────────────


class ResearchGoal(BaseModel):
    """What this round of experiments aims to verify."""

    summary: str = Field(description="One-sentence summary of the experiment goal")
    hypothesis: str = Field(description="The hypothesis being tested")
    success_criteria: list[str] = Field(
        default_factory=list,
        description="Concrete, measurable criteria for success",
    )


class DatasetSpec(BaseModel):
    """A dataset choice with rationale."""

    name: str
    split: str = "standard"
    rationale: str = ""


class MethodSpec(BaseModel):
    """A method (proposed, baseline, or ablation) in the experiment matrix."""

    name: str
    type: Literal["new_method", "baseline", "ablation"]
    implementation_status: Literal["needs_code", "needs_repro", "existing"] = "needs_code"
    rationale: str = ""


class MetricSpec(BaseModel):
    """An evaluation metric with rationale."""

    name: str
    rationale: str = ""


class ExperimentMatrix(BaseModel):
    """The cross-product space of the experiment: datasets × methods × metrics."""

    datasets: list[DatasetSpec] = Field(default_factory=list)
    methods: list[MethodSpec] = Field(default_factory=list)
    metrics: list[MetricSpec] = Field(default_factory=list)


class CodingTask(BaseModel):
    """A task for CodingAgent: implement or modify code.

    Field names align with CodingAgent's CodeTaskSpec for direct consumption.
    """

    id: str = Field(description="Unique task id, e.g. 'code_001'")
    repo_path: str = Field(description="Path to the target repository")
    task_goal: str = Field(description="What this coding task should accomplish")
    constraints: list[str] = Field(default_factory=list)
    verify_commands: list[str] = Field(default_factory=list)
    expected_artifacts: list[str] = Field(default_factory=list)
    rationale: str = Field(default="", description="Why this task is needed")


class ReproTask(BaseModel):
    """A task for ReproAgent: reproduce a baseline or SOTA method.

    Field names align with ReproAgent's ReproTask for direct consumption.
    """

    id: str = Field(description="Unique task id, e.g. 'repro_001'")
    paper_url: str = Field(description="URL to the paper to reproduce")
    repo_url: str = Field(description="URL to the official or community repository")
    experiment_goal: str = Field(description="Concrete reproduction goal")
    compute_budget: ComputeBudget | None = Field(default=None)
    expected_metrics: list[str] = Field(default_factory=list)
    rationale: str = Field(default="", description="Why this reproduction is needed")


class RunTask(BaseModel):
    """A task for the Runner: execute an experiment."""

    id: str = Field(description="Unique task id, e.g. 'run_001'")
    command_goal: str = Field(description="What this run should accomplish")
    expected_runtime: str = ""
    requires_gpu: bool = False
    rationale: str = Field(default="", description="Why this run is needed")


class TaskBundle(BaseModel):
    """All tasks generated by the experiment plan."""

    coding_tasks: list[CodingTask] = Field(default_factory=list)
    repro_tasks: list[ReproTask] = Field(default_factory=list)
    run_tasks: list[RunTask] = Field(default_factory=list)


class AnalysisPlan(BaseModel):
    """How to analyze results after experiments complete."""

    comparisons: list[str] = Field(default_factory=list, description="Which pairs to compare")
    plots: list[str] = Field(default_factory=list, description="Desired visualizations")
    failure_checks: list[str] = Field(
        default_factory=list,
        description="Things to check to avoid false conclusions",
    )


class Risk(BaseModel):
    """A risk with its mitigation strategy."""

    description: str
    mitigation: str = ""


class ExperimentPlan(BaseModel):
    """Complete structured experiment plan — the core output of ExpAgent."""

    version: int = 1
    goal: ResearchGoal
    experiment_matrix: ExperimentMatrix = Field(default_factory=ExperimentMatrix)
    tasks: TaskBundle = Field(default_factory=TaskBundle)
    analysis_plan: AnalysisPlan = Field(default_factory=AnalysisPlan)
    risks: list[Risk] = Field(default_factory=list)


class ValidationResult(BaseModel):
    """Result of deterministic plan validation."""

    status: Literal["ok", "needs_revision"]
    issues: list[str] = Field(default_factory=list)
