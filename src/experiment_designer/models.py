"""Pydantic data models for experiment design input and output."""

from __future__ import annotations

from typing import Annotated, Literal, Union

from pydantic import BaseModel, Field


# ── Input models ──────────────────────────────────────────────────


class ExistingMethod(BaseModel):
    """A method or code the user already has."""

    name: str
    location: str | None = Field(default=None, description="File or directory path")
    description: str = ""


class ExistingAssets(BaseModel):
    """What the user already has — code, data, known baselines.

    ExpAgent uses this to avoid planning duplicate work.
    The LLM infers everything else (missing baselines, ablations, etc.).
    """

    implemented_methods: list[ExistingMethod] = Field(default_factory=list)
    available_datasets: list[str] = Field(default_factory=list)
    known_baselines: list[str] = Field(default_factory=list)


class ComputeBudget(BaseModel):
    """Hardware and time constraints for the experiment."""

    gpu: str = "CPU only"
    max_runtime: str = "2 hours"
    max_trials: int = 10


class DesignInput(BaseModel):
    """Everything the user provides to kick off experiment design."""

    research_idea: str = Field(description="Natural language description of the research idea")
    target_task: str = Field(description="Task domain, e.g. 'image classification', 'time series forecasting'")
    compute_budget: ComputeBudget = Field(default_factory=ComputeBudget)
    constraints: list[str] = Field(default_factory=list)
    literature_context: list[str] = Field(default_factory=list)
    existing_assets: ExistingAssets = Field(default_factory=ExistingAssets)


# ── Output models ─────────────────────────────────────────────────


class ResearchGoal(BaseModel):
    """What this round of experiments aims to verify."""

    summary: str = Field(description="One-sentence summary of the experiment goal")
    hypothesis: str = Field(description="The hypothesis being tested")
    success_criteria: list[str] = Field(
        default_factory=list,
        description="Concrete, measurable criteria for success",
    )


class DatasetSpec(BaseModel):
    """A dataset choice with rationale."""

    name: str
    split: str = "standard"
    rationale: str = ""


class MethodSpec(BaseModel):
    """A method (proposed, baseline, or ablation) in the experiment matrix."""

    name: str
    type: Literal["new_method", "baseline", "ablation"]
    implementation_status: Literal["needs_code", "needs_repro", "existing"] = "needs_code"
    rationale: str = ""


class MetricSpec(BaseModel):
    """An evaluation metric with rationale."""

    name: str
    rationale: str = ""


class ExperimentMatrix(BaseModel):
    """The cross-product space of the experiment: datasets × methods × metrics."""

    datasets: list[DatasetSpec] = Field(default_factory=list)
    methods: list[MethodSpec] = Field(default_factory=list)
    metrics: list[MetricSpec] = Field(default_factory=list)


class CodingTask(BaseModel):
    """A task for CodingAgent: implement or modify code.

    Field names align with CodingAgent's CodeTaskSpec for direct consumption.
    """

    id: str = Field(description="Unique task id, e.g. 'code_001'")
    workspace_path: str = Field(description="Path to the target repository")
    task_goal: str = Field(description="What this coding task should accomplish")
    constraints: list[str] = Field(default_factory=list)
    verify_commands: list[str] = Field(default_factory=list)
    expected_artifacts: list[str] = Field(default_factory=list)
    rationale: str = Field(default="", description="Why this task is needed")


class ReproTask(BaseModel):
    """A task for ReproAgent: reproduce a baseline or SOTA method.

    Field names align with ReproAgent's ReproTask for direct consumption.
    """

    id: str = Field(description="Unique task id, e.g. 'repro_001'")
    paper_url: str = Field(description="URL to the paper to reproduce")
    repo_url: str = Field(description="URL to the official or community repository")
    experiment_goal: str = Field(description="Concrete reproduction goal")
    compute_budget: ComputeBudget | None = Field(default=None)
    expected_metrics: list[str] = Field(default_factory=list)
    rationale: str = Field(default="", description="Why this reproduction is needed")


class RunTask(BaseModel):
    """A task for the Runner: execute an experiment."""

    id: str = Field(description="Unique task id, e.g. 'run_001'")
    command_goal: str = Field(description="What this run should accomplish")
    expected_runtime: str = ""
    requires_gpu: bool = False
    rationale: str = Field(default="", description="Why this run is needed")


class TaskBundle(BaseModel):
    """All tasks generated by the experiment plan."""

    coding_tasks: list[CodingTask] = Field(default_factory=list)
    repro_tasks: list[ReproTask] = Field(default_factory=list)
    run_tasks: list[RunTask] = Field(default_factory=list)


class AnalysisPlan(BaseModel):
    """How to analyze results after experiments complete."""

    comparisons: list[str] = Field(default_factory=list, description="Which pairs to compare")
    plots: list[str] = Field(default_factory=list, description="Desired visualizations")
    failure_checks: list[str] = Field(
        default_factory=list,
        description="Things to check to avoid false conclusions",
    )


class Risk(BaseModel):
    """A risk with its mitigation strategy."""

    description: str
    mitigation: str = ""


class ExperimentPlan(BaseModel):
    """Complete structured experiment plan — the core output of ExpAgent."""

    version: int = 1
    goal: ResearchGoal
    experiment_matrix: ExperimentMatrix = Field(default_factory=ExperimentMatrix)
    tasks: TaskBundle = Field(default_factory=TaskBundle)
    analysis_plan: AnalysisPlan = Field(default_factory=AnalysisPlan)
    risks: list[Risk] = Field(default_factory=list)


class ValidationResult(BaseModel):
    """Result of deterministic plan validation."""

    status: Literal["ok", "needs_revision"]
    issues: list[str] = Field(default_factory=list)


# ── Scientific Advisor models ────────────────────────────────────


class ArtifactRef(BaseModel):
    """Reference to a result artifact passed by ResAgent.

    ExpAgent does not scan directories — ResAgent provides these.
    """

    id: str = Field(description="Unique artifact id, e.g. 'repro_result_001'")
    type: Literal["repro_result", "code_patch", "run_log", "metric_summary", "other"] = "other"
    path: str | None = Field(default=None, description="File path ExpAgent can read")
    summary: str = Field(default="", description="Brief summary provided by ResAgent")


class AdvisorContext(BaseModel):
    """Input to ExpAgent's advise() function — everything ExpAgent needs to know."""

    situation: str = Field(
        description="Natural language description of current situation. "
                    "ResAgent describes: the research idea, what happened, "
                    "what results were obtained, what failed, etc."
    )
    artifacts: list[ArtifactRef] = Field(
        default_factory=list,
        description="Relevant result files ExpAgent can read",
    )
    existing_plan: ExperimentPlan | None = Field(
        default=None,
        description="Current experiment plan, if one exists (for revision/analysis)",
    )
    thread_dir: str = Field(
        default="",
        description="Optional thread directory. If set, previous advisory summaries "
                    "are injected into the situation and new summaries appended."
    )
    parent_run: dict | None = Field(
        default=None,
        description="When orchestrated by ResAgent: {'module':'resagent','run_id':'res-...','task_id':'task_...'}."
    )


class ScientificConclusion(BaseModel):
    """The scientific conclusion ExpAgent reaches."""

    status: Literal[
        "supported", "not_supported", "inconclusive", "needs_more_experiments"
    ] = Field(description="Whether the evidence supports the hypothesis")
    rationale: str = Field(description="Scientific reasoning behind the conclusion")


class EvidenceItem(BaseModel):
    """One piece of evidence supporting the conclusion."""

    source: Literal["artifact", "literature", "reasoning"] = Field(
        description="Where this evidence came from"
    )
    description: str = Field(description="What this evidence shows")


# ── V2 scientific action contract ─────────────────────────────────
# Each recommended action is a discriminated union on `capability`.
# ExpAgent expresses scientific intent + a logical action graph only;
# it never emits executors, physical paths, or environment names.


class ScientificActionBase(BaseModel):
    """Common fields for every scientific action in a decision's action graph."""

    action_id: str = Field(description="Unique, non-empty id within this decision")
    capability: str = Field(description="Capability this action needs (union discriminator)")
    objective: str = Field(description="One-sentence scientific objective of this action")
    rationale: str = Field(description="Scientific justification — WHY this action")
    depends_on: list[str] = Field(
        default_factory=list,
        description="action_ids of earlier actions that must complete first",
    )
    project_ref: str = Field(
        default="",
        description="Logical project identity shared across actions touching one repository",
    )
    required: bool = Field(
        default=True,
        description="Whether ResAgent must complete this action before finishing",
    )
    success_criteria: list[str] = Field(
        default_factory=list,
        description="Concrete, measurable success criteria",
    )


class ModifyCodeAction(ScientificActionBase):
    """Implement or modify experiment code (CodingAgent)."""

    capability: Literal["modify_code"] = "modify_code"
    constraints: list[str] = Field(default_factory=list)
    verify_commands: list[str] = Field(default_factory=list)
    expected_artifacts: list[str] = Field(default_factory=list)


class ReproduceExperimentAction(ScientificActionBase):
    """Reproduce a method from a paper/repo (experiment operator)."""

    capability: Literal["reproduce_experiment"] = "reproduce_experiment"
    paper_url: str = ""
    repo_url: str = ""
    code_availability: Literal["public", "upon_request", "none", ""] = ""
    compute_budget: ComputeBudget | None = None
    expected_metrics: list[str] = Field(default_factory=list)


class ExecuteExperimentAction(ScientificActionBase):
    """Execute an experiment in an existing project (experiment operator)."""

    capability: Literal["execute_experiment"] = "execute_experiment"
    requires_gpu: bool = False
    expected_metrics: list[str] = Field(default_factory=list)


class AnalyzeResultsAction(ScientificActionBase):
    """Interpret metrics, compare methods, or judge a hypothesis (ExpAgent)."""

    capability: Literal["analyze_results"] = "analyze_results"


class SearchLiteratureAction(ScientificActionBase):
    """Search and analyze relevant papers (ExpAgent)."""

    capability: Literal["search_literature"] = "search_literature"
    search_query: str = ""


class AskUserAction(ScientificActionBase):
    """Request necessary human input (ResAgent)."""

    capability: Literal["ask_user"] = "ask_user"
    question: str = ""


ScientificAction = Annotated[
    Union[
        ModifyCodeAction,
        ReproduceExperimentAction,
        ExecuteExperimentAction,
        AnalyzeResultsAction,
        SearchLiteratureAction,
        AskUserAction,
    ],
    Field(discriminator="capability"),
]


class ResultAnalysis(BaseModel):
    """Analysis of experiment results (embedded in ScientificDecision when relevant)."""

    summary: str = Field(default="", description="One-paragraph analysis summary")
    findings: list[str] = Field(default_factory=list, description="Key findings from the results")


class FailureDiagnosis(BaseModel):
    """Diagnosis of an experiment failure (embedded in ScientificDecision when relevant)."""

    failure_type: Literal["transient", "system", "scientific", "code", "data", "budget"] = Field(
        default="scientific",
        description="Classified failure category",
    )
    diagnosis: str = Field(default="", description="What went wrong, scientifically speaking")
    is_recoverable: bool = Field(default=True, description="Whether the experiment can be salvaged")


class ScientificDecision(BaseModel):
    """Unified output of ExpAgent — the scientific advisor's verdict.

    This is THE output that ResAgent consumes. It combines:
    - A scientific conclusion with confidence
    - Supporting evidence
    - Optional embedded experiment plan (for design/revision modes)
    - Optional result analysis (for analyze mode)
    - Optional failure diagnosis (for failure mode)
    - A logical scientific action graph (typed by capability)
    """

    summary: str = Field(description="One-sentence summary of the scientific decision")
    confidence: Literal["high", "medium", "low"] = Field(
        description="How confident ExpAgent is in this conclusion"
    )

    conclusion: ScientificConclusion | None = Field(
        default=None,
        description="The scientific verdict. None for pure explanation/discussion requests."
    )
    evidence: list[EvidenceItem] = Field(
        default_factory=list,
        description="Evidence supporting the conclusion",
    )

    experiment_plan: ExperimentPlan | None = Field(
        default=None,
        description="Embedded experiment plan (present when designing or revising experiments)",
    )
    result_analysis: ResultAnalysis | None = Field(
        default=None,
        description="Analysis of experiment results (present when analyzing results)",
    )
    failure_diagnosis: FailureDiagnosis | None = Field(
        default=None,
        description="Failure diagnosis (present when diagnosing failures)",
    )

    recommended_actions: list[ScientificAction] = Field(
        default_factory=list,
        description="Logical scientific action graph. Each element is a typed "
                    "ScientificAction discriminated on capability.",
    )
    analysis_required: bool = Field(
        default=True,
        description="Whether terminal experiments must be covered by an "
                    "analyze_results action before the run can finish. Set "
                    "False only for pure engineering smoke tests.",
    )

    risks: list[str] = Field(
        default_factory=list,
        description="Scientific risks ExpAgent identified",
    )
    needs_user_input: list[str] = Field(
        default_factory=list,
        description="Questions that need human answers before proceeding",
    )


